"""Trim the cut-outs, measure head / feet / body length, write src/mosquito/sprites.ts.

HEAD = largest inscribed disc of the hole-filled *body-coloured* region (the mosquito's wings are big pale ovals,
so the plain silhouette would put the 'head' in the wing area). BODY LENGTH = horizontal extent of the
body-coloured pixels (head front to abdomen tip, the needle nose is thin and excluded by an opening).
"""
import json, os
import numpy as np, cv2
from PIL import Image

ROOT = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(ROOT, '..', '..'))
OUT = os.path.join(PROJ, 'public', 'mosquito', 'sprites')
os.makedirs(OUT, exist_ok=True)
PAD = 12
names = ['hover', 'scared_up', 'squished', 'tumble', 'smug', 'drop']
meta = {}
for n in names:
    im = np.array(Image.open(os.path.join(ROOT, 'raw', f'{n}.png')).convert('RGBA'))
    a = im[..., 3]
    ys, xs = np.where(a > 8)
    y0, y1 = max(ys.min() - PAD, 0), min(ys.max() + PAD + 1, im.shape[0])
    x0, x1 = max(xs.min() - PAD, 0), min(xs.max() + PAD + 1, im.shape[1])
    crop = im[y0:y1, x0:x1].copy()
    Image.fromarray(crop).save(os.path.join(OUT, f'{n}.png'), optimize=True)
    h, w = crop.shape[:2]
    rgb = crop[..., :3].astype(np.int32); al = crop[..., 3]
    entry = {'w': int(w), 'h': int(h), 'trim': [int(x0), int(y0)]}
    if n == 'drop':
        solid = (al > 128).astype(np.uint8)
        dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
        cy, cx = np.unravel_index(dt.argmax(), dt.shape)
        ys2, xs2 = np.where(al > 128)
        entry.update({'center': [int(cx), int(cy)], 'r': float(dt[cy, cx]), 'bottom': int(ys2.max()), 'top': int(ys2.min()),
                      'left': int(xs2.min()), 'right': int(xs2.max())})
    else:
        # body colour: warm grey-brown, both light (#A39283-ish) and the soft shade; exclude pale wings / black ink
        r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
        lum = (r + g + b) / 3
        body = (al > 200) & (r > g) & (g >= b - 6) & (lum > 95) & (lum < 215) & ((r - b) > 12)
        body = body.astype(np.uint8)
        body = cv2.morphologyEx(body, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
        ff = body.copy(); mask = np.zeros((h + 2, w + 2), np.uint8)
        cv2.floodFill(ff, mask, (0, 0), 2)
        filled = np.where(ff == 2, 0, 1).astype(np.uint8)
        dt = cv2.distanceTransform(filled, cv2.DIST_L2, 5)
        hy, hx = np.unravel_index(dt.argmax(), dt.shape)
        hr = float(dt[hy, hx])
        # body length: open away thin parts (nose, legs) then take horizontal extent of the biggest blobs
        k = max(5, int(hr * 0.35)) | 1
        opened = cv2.morphologyEx(filled, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k)))
        cnt, lab, stats, _ = cv2.connectedComponentsWithStats(opened)
        keep = np.zeros_like(opened)
        for i in range(1, cnt):
            if stats[i, cv2.CC_STAT_AREA] > 0.04 * stats[1:, cv2.CC_STAT_AREA].max():
                keep[lab == i] = 1
        bys, bxs = np.where(keep > 0)
        # feet: middle of opaque pixels in the bottom 3.5 % rows of the whole cut-out
        ys3, xs3 = np.where(al > 128)
        band = ys3 >= ys3.max() - 0.035 * (ys3.max() - ys3.min())
        wing = (al > 200) & (b > r + 12) & ((r + g + b) / 3 > 190)
        wys, wxs = np.where(wing)
        it, il = np.argmin(wys), np.argmin(wxs)
        entry.update({'wingTop': [int(wxs[it]), int(wys[it])], 'wingLeft': [int(wxs[il]), int(wys[il])]})
        entry.update({'head': [int(hx), int(hy)], 'headR': hr,
                      'body': [int(bxs.min()), int(bys.min()), int(bxs.max()), int(bys.max())],
                      'feet': [float(xs3[band].mean()), float(ys3.max())]})
        dbg = cv2.cvtColor(crop, cv2.COLOR_RGBA2BGRA).copy()
        dbg[keep > 0] = (dbg[keep > 0] * 0.5 + np.array([0, 0, 255, 255]) * 0.5).astype(np.uint8)
        cv2.circle(dbg, (int(hx), int(hy)), int(hr), (255, 0, 0, 255), 6)
        cv2.rectangle(dbg, (int(bxs.min()), int(bys.min())), (int(bxs.max()), int(bys.max())), (0, 200, 0, 255), 4)
        cv2.circle(dbg, (int(entry['feet'][0]), int(entry['feet'][1])), 18, (0, 255, 255, 255), -1)
        bg = np.full_like(dbg, 255); m = dbg[..., 3:4] / 255.0
        comp = (dbg[..., :3] * m + bg[..., :3] * (1 - m)).astype(np.uint8)
        cv2.imwrite(os.path.join(ROOT, 'qa', f'measure_{n}.png'), cv2.resize(comp, (w // 3, h // 3)))
    meta[n] = entry
    print(n, json.dumps(entry))

os.makedirs(os.path.join(PROJ, 'src', 'mosquito'), exist_ok=True)
with open(os.path.join(PROJ, 'src', 'mosquito', 'sprites.ts'), 'w') as f:
    f.write('// Generated by images/mosquito/prep.py - trimmed sprite sizes and measured anchor points (sprite px).\n')
    f.write('export const SPRITES = ' + json.dumps(meta, indent=2) + ' as const;\n')
    f.write('export type PoseName = Exclude<keyof typeof SPRITES, "drop">;\n')

# the drop's baked outline is thinned after trimming (see thin_drop.py)
import runpy
runpy.run_path(os.path.join(ROOT, 'thin_drop.py'))
